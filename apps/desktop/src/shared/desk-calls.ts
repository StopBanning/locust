/*
 * WHAT LOCUST IN A BROWSER MAY DO (0.830, "Away from your desk", step 3). The window in a browser makes the same calls
 * as the window on this computer (desktop-api.ts), and the computer answers each by this list: a call to read, a call
 * that acts -- in this release, what the phone already did and the rest of a conversation's own steps -- or, for
 * anything not listed, a call that stays in the window on this computer. Signing agents in, permissions and the rules
 * that grant them, the organization's policy, what may be spent, the terminal, installing, pairing more devices, and
 * anything that opens a dialog or a window on this computer are never listed.
 *
 * A call added to the window is window-only until it is listed here: the-browser-asks-only-what-it-may.test.ts reads
 * desktop-api.ts and fails on any call this file does not name.
 *
 * ROUTINES AND ROOMS FROM A BROWSER (0.834). A routine is made, changed, paused, run, removed and its copy's changes
 * kept or discarded from a browser as in the window; a room is made, renamed, removed, posted to and its board moved.
 * Choosing a folder, importing or exporting a file, and showing a copy in the file manager open something on this
 * computer, so they stay here. A teammate is made, changed and removed too -- but its monthly limit is what may be
 * spent, so a change that says one stays here, as do its folder, connectors, skills and keys.
 *
 * COMPARE FROM A BROWSER (0.835). A comparison is started, asked again, judged, run again, and a column kept, from a
 * browser as in the window: its models are the ones a turn started there may already run on. So are the light or
 * dark look, groups, what teammates remember (all but forgetting everything at once), and Scout's notes, tune-up and
 * settings -- all but letting Scout prepare fixes, which runs models on its own. The folder's own settings hold Auto
 * and what teammates may reach, so they stay here.
 *
 * COMMIT AND LAND FROM A BROWSER (0.835). A commit is drafted and made, and a teammate's branch landed or its merge
 * begun, from a browser too. Pushing and opening a pull request put the work on GitHub for others to see, and
 * throwing a teammate's branch away cannot be undone, so those stay here.
 */
export type DeskAccess = 'read' | 'act'


const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value)
const reads = new Set(READ)
const acts = new Set(ACT)

/** How a browser may make this call with these arguments, or undefined when it stays in the window on this computer. */
export function deskAccess(channel: string, args: readonly unknown[]): DeskAccess | undefined {
  if (reads.has(channel)) return 'read'
  if (acts.has(channel)) return 'act'
  return SOME[channel]?.(args)
}

